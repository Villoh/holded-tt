"""Windows Task Scheduler backend for automatic clocking.

The same design as the systemd one (see units.py), expressed as scheduled tasks:

* ``\\holded-tt\\holded-tt-plan`` plans the day every weekday at ``--plan-at`` and again at
  logon, running ``clock tick --schedule``. It is the timer and the login service in one.
* ``\\holded-tt\\holded-tt-next-<UTC stamp>`` is the one-shot task `--schedule` arms for the
  next event. Like the systemd units, its name carries the time, so arming the same event
  twice reuses one task.

Tasks are defined in XML, because ``schtasks`` flags cannot express several triggers or
"run if a start was missed". They run as the current user, only while logged on
(no password is stored).

What systemd does natively and this does not: retries (the app re-arms them) and the
``OnFailure=`` alert, so a failed run only shows in the task history (and in `clock plan`'s warning when the next event is not armed).
"""

from __future__ import annotations

import csv
import io
import os
import re
import subprocess
import tempfile
from collections.abc import Callable
from datetime import datetime, timedelta, timezone
from pathlib import Path
from typing import Any
from xml.etree import ElementTree as ET
from xml.sax.saxutils import escape

from holded_tt.errors import HoldedCliError
from holded_tt.exit_codes import EXIT_NO_RETRY
from holded_tt.units import check_plan_time

# Task Scheduler's "restart on failure" does NOT restart a task whose program exits non-zero
# (checked on a windows-latest runner: one run, Last Result 2, no restart in 5 minutes), so
# `clock tick --schedule` re-arms its own retry instead. See autoclock.note_failure.
RETRIES_NATIVELY = False

FOLDER = "\\holded-tt"
PLAN_TASK = f"{FOLDER}\\holded-tt-plan"
NEXT_PREFIX = f"{FOLDER}\\holded-tt-next-"
MARKER = "Generated by `holded-tt clock install`. Reinstall to regenerate."
WEEKDAYS = ("Monday", "Tuesday", "Wednesday", "Thursday", "Friday")
EXPIRE_AFTER = timedelta(hours=1)  # a fired one-shot task is deleted this long after its time

Runner = Callable[..., Any]
_NEXT_NAME = re.compile(r"\\holded-tt\\holded-tt-next-(\d{8}T\d{6})$")
_XML_DECLARATION = re.compile(r"^\s*<\?xml[^>]*\?>")


def _duration(seconds: int) -> str:
    return f"PT{max(1, seconds // 60)}M"  # Task Scheduler's restart interval is at least 1 minute


def _user_id() -> str | None:
    user = os.environ.get("USERNAME")
    domain = os.environ.get("USERDOMAIN")
    return f"{domain}\\{user}" if user and domain else user


def _settings(expire: bool) -> str:
    delete = f"<DeleteExpiredTaskAfter>{_duration(int(EXPIRE_AFTER.total_seconds()))}</DeleteExpiredTaskAfter>" if expire else ""
    return (
        "<MultipleInstancesPolicy>IgnoreNew</MultipleInstancesPolicy>"
        "<DisallowStartIfOnBatteries>false</DisallowStartIfOnBatteries>"
        "<StopIfGoingOnBatteries>false</StopIfGoingOnBatteries>"
        "<StartWhenAvailable>true</StartWhenAvailable>"  # run a missed start as soon as possible
        "<AllowStartOnDemand>true</AllowStartOnDemand>"
        "<ExecutionTimeLimit>PT10M</ExecutionTimeLimit>"
        f"{delete}<Enabled>true</Enabled>"
    )


def _document(triggers: str, exe: str, expire: bool) -> str:
    return (
        '<?xml version="1.0" encoding="UTF-16"?>\n'
        '<Task version="1.2" xmlns="http://schemas.microsoft.com/windows/2004/02/mit/task">'
        f"<RegistrationInfo><Description>{escape(MARKER)}</Description></RegistrationInfo>"
        f"<Triggers>{triggers}</Triggers>"
        '<Principals><Principal id="Author"><LogonType>InteractiveToken</LogonType>'
        "<RunLevel>LeastPrivilege</RunLevel></Principal></Principals>"
        f"<Settings>{_settings(expire)}</Settings>"
        '<Actions Context="Author"><Exec>'
        f"<Command>{escape(exe)}</Command><Arguments>clock tick --schedule</Arguments>"
        "</Exec></Actions></Task>\n"
    )


def plan_xml(exe: str, plan_at: str, today: datetime | None = None) -> str:
    """The daily planning task: weekdays at ``plan_at`` plus every logon of this user."""
    check_plan_time(plan_at)
    day = (today or datetime.now()).date()
    days = "".join(f"<{d}/>" for d in WEEKDAYS)
    user = _user_id()
    logon_user = f"<UserId>{escape(user)}</UserId>" if user else ""
    triggers = (
        f"<CalendarTrigger><StartBoundary>{day:%Y-%m-%d}T{plan_at}:00</StartBoundary><Enabled>true</Enabled>"
        f"<ScheduleByWeek><DaysOfWeek>{days}</DaysOfWeek><WeeksInterval>1</WeeksInterval></ScheduleByWeek>"
        "</CalendarTrigger>"
        f"<LogonTrigger><Enabled>true</Enabled>{logon_user}</LogonTrigger>"
    )
    return _document(triggers, exe, expire=False)


def next_xml(when: datetime, exe: str) -> str:
    """A one-shot task for ``when`` (timezone-aware), to the second."""
    start = when.isoformat(timespec="seconds")
    end = (when + EXPIRE_AFTER).isoformat(timespec="seconds")
    triggers = (
        f"<TimeTrigger><StartBoundary>{start}</StartBoundary><EndBoundary>{end}</EndBoundary>"
        "<Enabled>true</Enabled></TimeTrigger>"
    )
    return _document(triggers, exe, expire=True)


def next_task_name(when: datetime) -> str:
    return f"{NEXT_PREFIX}{when.astimezone(timezone.utc):%Y%m%dT%H%M%S}"


def _parse(xml_text: str) -> ET.Element:
    return ET.fromstring(_XML_DECLARATION.sub("", xml_text, count=1))


def _local(tag: str) -> str:
    return tag.rsplit("}", 1)[-1]


def _no_schtasks() -> HoldedCliError:
    return HoldedCliError(
        message="schtasks not found: automatic clocking needs the Windows Task Scheduler.",
        hint="Run `holded-tt clock tick` from a periodic task every 5 minutes instead.",
        exit_code=EXIT_NO_RETRY,
    )


def _schtasks(run: Runner, *args: str, check: bool = True) -> Any:
    try:
        done = run(["schtasks", *args], capture_output=True, text=True)
    except FileNotFoundError:
        raise _no_schtasks() from None
    if check and done.returncode:
        detail = (done.stderr or done.stdout or "").strip()
        raise HoldedCliError(
            message=f"schtasks {' '.join(args[:2])} failed.",
            hint=detail or f"exit status {done.returncode}",
        )
    return done


def _register(run: Runner, name: str, xml: str) -> None:
    """Create or replace ``name`` from ``xml``. schtasks wants UTF-16 with a BOM."""
    handle, tmp = tempfile.mkstemp(suffix=".xml", prefix="holded-tt-")
    os.close(handle)
    path = Path(tmp)
    try:
        path.write_bytes(xml.encode("utf-16"))
        _schtasks(run, "/Create", "/TN", name, "/XML", str(path), "/F")
    finally:
        path.unlink(missing_ok=True)


def _task_names(run: Runner) -> list[str] | None:
    """Names of our one-shot tasks, or None when the Task Scheduler cannot be asked."""
    try:
        done = run(["schtasks", "/Query", "/FO", "CSV", "/NH"], capture_output=True, text=True)
    except FileNotFoundError:
        return None
    if done.returncode:
        return None
    names = []
    for row in csv.reader(io.StringIO(done.stdout or "")):
        if row and _NEXT_NAME.search(row[0]):
            names.append(row[0])
    return names


def _stamp(name: str) -> datetime:
    match = _NEXT_NAME.search(name)
    assert match is not None
    return datetime.strptime(match.group(1), "%Y%m%dT%H%M%S").replace(tzinfo=timezone.utc)


def armed_events(run: Runner = subprocess.run, now: datetime | None = None) -> list[datetime] | None:
    """When each pending one-shot task fires (UTC). Tasks already past are not "armed"."""
    names = _task_names(run)
    if names is None:
        return None
    moment = now or datetime.now(timezone.utc)
    return sorted(t for t in map(_stamp, names) if t > moment)


def arm_at(when: datetime, exe: str, run: Runner = subprocess.run) -> None:
    """Arm a one-shot task that runs `exe clock tick --schedule` at ``when``.

    Re-registering the same name replaces it (``/F``), so a retry never fires twice.
    Tasks that fired long ago are removed here, as a backup to DeleteExpiredTaskAfter.
    """
    try:
        _register(run, next_task_name(when), next_xml(when, exe))
    except HoldedCliError as error:
        if error.exit_code == EXIT_NO_RETRY:
            raise
        raise HoldedCliError(
            message="Could not schedule the next clock event.", hint=error.hint
        ) from None
    cutoff = datetime.now(timezone.utc) - EXPIRE_AFTER
    for name in _task_names(run) or []:
        if _stamp(name) < cutoff:
            _schtasks(run, "/Delete", "/TN", name, "/F", check=False)


def disarm(run: Runner = subprocess.run) -> None:
    """Delete every armed one-shot task. Quiet where there is no Task Scheduler."""
    for name in _task_names(run) or []:
        _schtasks(run, "/Delete", "/TN", name, "/F", check=False)


def _plan_task_xml(run: Runner) -> str | None:
    try:
        done = run(["schtasks", "/Query", "/TN", PLAN_TASK, "/XML"], capture_output=True, text=True)
    except FileNotFoundError:
        return None
    return done.stdout if not done.returncode and done.stdout else None


def next_planning(run: Runner = subprocess.run, now: datetime | None = None) -> str | None:
    """When the planning task fires next (local time), computed from its own definition."""
    text = _plan_task_xml(run)
    if text is None:
        return None
    root = _parse(text)
    start = next((e.text for e in root.iter() if _local(e.tag) == "StartBoundary" and e.text), None)
    days = {_local(e.tag) for e in root.iter() if _local(e.tag) in WEEKDAYS}
    if start is None or not days:
        return None
    clock = datetime.fromisoformat(start).time()
    moment = now or datetime.now()
    for offset in range(8):
        candidate = datetime.combine(moment.date() + timedelta(days=offset), clock)
        if candidate > moment and candidate.strftime("%A") in days:
            return f"{candidate:%a %Y-%m-%d %H:%M:%S}"
    return None


def _check_not_foreign(run: Runner) -> None:
    text = _plan_task_xml(run)
    if text is None:
        return
    description = next((e.text for e in _parse(text).iter() if _local(e.tag) == "Description"), None)
    if not (description or "").startswith(MARKER):
        raise HoldedCliError(
            message=f"The task {PLAN_TASK} exists and was not generated by holded-tt.",
            hint="Delete or rename it and run install again; it is not overwritten.",
        )


def install(
    exe: str,
    plan_at: str = "06:00",
    dry_run: bool = False,
    run: Runner = subprocess.run,
) -> list[str]:
    """Create the planning task. Returns the lines to show the user."""
    xml = plan_xml(exe, plan_at)
    _check_not_foreign(run)
    if dry_run:
        return [
            f"--- task {PLAN_TASK}", xml.rstrip(), "",
            f"would: schtasks /Create /TN {PLAN_TASK} /XML <file> /F",
            "(it is created but not run: nothing is clocked until its next trigger)",
        ]
    _register(run, PLAN_TASK, xml)
    return [
        f"created task {PLAN_TASK}",
        f"plans the day at {plan_at} Mon-Fri and at every logon; runs only while you are logged on",
    ]


def uninstall(run: Runner = subprocess.run) -> list[str]:
    """Delete the planning task and any armed one-shot task."""
    out: list[str] = []
    if _plan_task_xml(run) is not None:
        try:
            _check_not_foreign(run)
        except HoldedCliError:
            out.append(f"left {PLAN_TASK} alone (not generated by holded-tt)")
        else:
            _schtasks(run, "/Delete", "/TN", PLAN_TASK, "/F", check=False)
            out.append(f"removed {PLAN_TASK}")
    armed = _task_names(run) or []
    disarm(run)
    out += [f"removed {name}" for name in armed]
    return out or ["nothing to remove"]
