"""systemd user units for automatic clocking (`clock install` / `clock uninstall`).

Three units: a timer that plans the day every weekday morning, the service it (and
the user manager's start-up) runs as `clock tick --schedule`, and an alert unit.
Every one-shot timer that `--schedule` arms later reuses the retry settings below,
so the generated service and `autoclock.arm_next` cannot drift apart.
"""

from __future__ import annotations

import os
import re
import shutil
import subprocess
from collections.abc import Callable
from pathlib import Path
from typing import Any

from holded_tt.errors import HoldedCliError, InputError
from holded_tt.exit_codes import EXIT_NO_RETRY

MARKER = "# Generated by `holded-tt clock install`. Reinstall to regenerate."
TICK_SERVICE = "holded-tt-tick.service"
TICK_TIMER = "holded-tt-tick.timer"
FAILED_SERVICE = "holded-tt-failed.service"
ARMED_PATTERN = "holded-tt-next-*"  # the one-shot units `--schedule` arms

UNIT_RETRY = (
    f"OnFailure={FAILED_SERVICE}",
    "StartLimitBurst=15",  # 15 attempts, 2 minutes apart: about 30 minutes of retries
    "StartLimitIntervalSec=1h",
)
SERVICE_RETRY = (
    "Restart=on-failure",
    "RestartSec=120",
    f"RestartPreventExitStatus={EXIT_NO_RETRY}",  # a missed clock-in cannot be retried away
)
RETRY_PROPERTIES = UNIT_RETRY + SERVICE_RETRY

_HHMM = re.compile(r"^([01]\d|2[0-3]):[0-5]\d$")
Runner = Callable[..., Any]


def unit_dir() -> Path:
    base = os.environ.get("XDG_CONFIG_HOME") or str(Path.home() / ".config")
    return Path(base) / "systemd" / "user"


def _quote(arg: str) -> str:
    arg = arg.replace("%", "%%")  # systemd specifier
    return f'"{arg}"' if " " in arg else arg


def render_units(exe: str, plan_at: str = "06:00", notify: str | None = None) -> dict[str, str]:
    """Unit file name -> text. ``notify`` is the absolute path of `notify-send`, if any."""
    if not _HHMM.match(plan_at):
        raise InputError(
            message=f"Invalid time: {plan_at!r}.",
            hint="Use HH:MM, e.g. --plan-at 06:00.",
        )
    nl = "\n".join
    if notify:
        alert = f"{_quote(notify)} holded-tt \"clock tick failed, see: journalctl --user -u 'holded-tt-*'\""
    else:  # no desktop notifier: at least leave a line in the journal
        sh = shutil.which("sh") or "/bin/sh"
        alert = f"{_quote(sh)} -c \"echo 'holded-tt: clock tick failed, see journalctl --user -u holded-tt-*'\""
    return {
        TICK_TIMER: nl([
            MARKER, "[Unit]", "Description=Plan the holded-tt day", "",
            "[Timer]", f"OnCalendar=Mon..Fri *-*-* {plan_at}:00", "Persistent=true", "",
            "[Install]", "WantedBy=timers.target", "",
        ]),
        TICK_SERVICE: nl([
            MARKER, "[Unit]", "Description=holded-tt clock tick", *UNIT_RETRY, "",
            "[Service]", "Type=oneshot",
            f"ExecStart={_quote(exe)} clock tick --schedule", *SERVICE_RETRY, "",
            "[Install]", "WantedBy=default.target", "",
        ]),
        FAILED_SERVICE: nl([
            MARKER, "[Unit]", "Description=holded-tt tick failed",
            "StartLimitBurst=1", "StartLimitIntervalSec=1h", "",  # alert once an hour
            "[Service]", "Type=oneshot", f"ExecStart={alert}", "",
        ]),
    }


def _is_ours(path: Path) -> bool:
    try:
        return path.read_text().startswith(MARKER)
    except OSError:
        return False


def _check_writable(path: Path) -> None:
    if path.is_symlink():
        raise HoldedCliError(
            message=f"{path} is a symlink (managed by home-manager or similar).",
            hint="Declare the units there instead, or remove the link and run install again.",
        )
    if path.exists() and not _is_ours(path):
        raise HoldedCliError(
            message=f"{path} exists and was not generated by holded-tt.",
            hint="Move it away and run install again; it is not overwritten.",
        )


def _systemctl(run: Runner, *args: str, check: bool = True) -> None:
    systemctl = shutil.which("systemctl")
    if systemctl is None:
        raise HoldedCliError(
            message="systemctl not found: automatic clocking with --schedule needs systemd (Linux).",
            hint="On macOS or Windows run `holded-tt clock tick` from a timer every 5 minutes instead.",
        )
    done = run([systemctl, "--user", *args], capture_output=True, text=True)
    if check and done.returncode:
        raise HoldedCliError(
            message=f"systemctl --user {' '.join(args)} failed.",
            hint=done.stderr.strip() or f"exit status {done.returncode}",
        )


def install(
    exe: str,
    plan_at: str = "06:00",
    dry_run: bool = False,
    run: Runner = subprocess.run,
    directory: Path | None = None,
    notify: str | None = None,
) -> list[str]:
    """Write the units and enable them. Returns the lines to show the user."""
    directory = directory or unit_dir()
    units = render_units(exe, plan_at, notify if notify is not None else shutil.which("notify-send"))
    for name in units:
        _check_writable(directory / name)
    if dry_run:
        out: list[str] = []
        for name, text in units.items():
            out += [f"--- {directory / name}", text.rstrip()]
        return out + ["", "would: systemctl --user daemon-reload",
                      f"would: systemctl --user enable --now {TICK_TIMER}",
                      f"would: systemctl --user enable {TICK_SERVICE}"]

    directory.mkdir(parents=True, exist_ok=True)
    for name, text in units.items():
        (directory / name).write_text(text)
    _systemctl(run, "daemon-reload")
    _systemctl(run, "enable", "--now", TICK_TIMER)
    _systemctl(run, "enable", TICK_SERVICE)  # no --now: starting it runs a real tick
    return [f"wrote {directory / name}" for name in units] + [
        f"enabled {TICK_TIMER} (plans the day at {plan_at}, Mon-Fri) and {TICK_SERVICE} (runs at login)",
    ]


def uninstall(run: Runner = subprocess.run, directory: Path | None = None) -> list[str]:
    """Disable and remove the units, and stop any armed one-shot timer."""
    directory = directory or unit_dir()
    _systemctl(run, "disable", "--now", TICK_TIMER, check=False)
    _systemctl(run, "disable", TICK_SERVICE, check=False)
    _systemctl(run, "stop", ARMED_PATTERN, check=False)
    out: list[str] = []
    for name in (TICK_TIMER, TICK_SERVICE, FAILED_SERVICE):
        path = directory / name
        if path.is_symlink() or (path.exists() and not _is_ours(path)):
            out.append(f"left {path} alone (not generated by holded-tt)")
        elif path.exists():
            path.unlink()
            out.append(f"removed {path}")
    _systemctl(run, "daemon-reload", check=False)
    return out or ["nothing to remove"]
